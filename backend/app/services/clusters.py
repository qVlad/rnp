def cluster_for_warehouse(name: str | None) -> str:
    """Вернуть код кластера по имени склада WB. 'OTHER' если не распознали."""
    if not name:
        return "OTHER"
    s = name.lower()
    for kw, code in _WAREHOUSE_KEYWORDS:
        if kw in s:
            return code
    return "OTHER"


# Округа РФ → кластеры. WB передаёт `oblast` точно одной из этих строк.
_OBLAST_TO_CLUSTER: dict[str, str] = {
    "Центральный федеральный округ": "CFO",
    "Северо-Западный федеральный округ": "NWFO",
    "Южный федеральный округ": "SFO",
    "Северо-Кавказский федеральный округ": "SFO",
    "Приволжский федеральный округ": "VFO",
    "Уральский федеральный округ": "UFO",
    "Сибирский федеральный округ": "SIB",
    "Дальневосточный федеральный округ": "DVFO",
}


def cluster_for_oblast(oblast: str | None, region_name: str | None = None) -> str:
    """Вернуть код кластера по oblast. Fallback на region_name (для зарубежа)."""
    if oblast:
        if oblast in _OBLAST_TO_CLUSTER:
            return _OBLAST_TO_CLUSTER[oblast]
    if region_name:
        # Беларусь / Казахстан / Узбекистан / etc. приходят пустым oblast
        # и неРФ region_name.
        rl = region_name.lower()
        if any(x in rl for x in ("беларус", "казахст", "узбек", "армени", "грузи", "таджик", "кыргыз")):
            return "INTL"
    return "OTHER"


def cluster_label(code: str) -> str:
    return CLUSTER_LABELS.get(code, code)
